    <h1>Financiamento Não Disponível</h1>

    <h2>O que significa?</h2>
    <p>Nem todos os imóveis da Caixa aceitam financiamento habitacional. A modalidade de venda e as condições do edital determinam se é possível ou não financiar a compra.</p>

    <h2>Modalidades e financiamento</h2>
    <ul>
      <li><strong>Venda Direta Online:</strong> geralmente <strong>aceita financiamento</strong> (até 95% do valor)</li>
      <li><strong>Leilão SFI (Edital Único):</strong> geralmente <strong>não aceita</strong> — pagamento à vista ou parcelamento curto</li>
      <li><strong>Licitação Aberta:</strong> pode aceitar — depende do edital</li>
      <li><strong>Venda Online:</strong> varia por edital</li>
    </ul>

    <h2>Por que é um risco?</h2>
    <ul>
      <li>Comprador dá lance achando que vai financiar, mas o edital não permite</li>
      <li>Não ter o valor à vista no prazo = perda do lance + penalidade</li>
      <li>Mesmo quando aceita financiamento, o banco pode <strong>negar o crédito</strong> após a arrematação (imóvel com problemas documentais)</li>
    </ul>

    <h2>Uso de FGTS</h2>
    <p>O uso de FGTS é permitido em algumas modalidades, mas com restrições:</p>
    <ul>
      <li>Imóvel deve ser residencial e urbano</li>
      <li>Comprador não pode ter outro imóvel na mesma cidade</li>
      <li>Imóvel deve estar dentro do limite de valor do SFH</li>
      <li>Verificar se o edital autoriza expressamente</li>
    </ul>

    <h2>Como se proteger</h2>
    <ul>
      <li><strong>Verifique no edital</strong> se aceita financiamento antes de dar lance</li>
      <li>No Imovue, use o filtro <strong>"Financiamento: Sim"</strong> para ver apenas imóveis financiáveis</li>
      <li>Se pretende financiar, obtenha a carta de crédito <strong>pré-aprovada</strong> antes de participar</li>
      <li>Para leilões que exigem pagamento à vista: tenha o valor disponível em conta</li>
    </ul>
  </div>
