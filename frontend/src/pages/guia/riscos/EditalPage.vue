    <h1>Edital com Regras Específicas</h1>

    <h2>O que é o edital?</h2>
    <p>O edital é o documento oficial que rege a venda. Ele é <strong>o contrato antes do contrato</strong> — define todas as regras: quem pode participar, como pagar, prazos, comissões, penalidades e responsabilidades.</p>

    <h2>Por que é um risco?</h2>
    <ul>
      <li>Cada imóvel pode ter um edital <strong>com regras diferentes</strong></li>
      <li>Ignorar uma cláusula pode resultar em <strong>perda do lance, multa e exclusão</strong></li>
      <li>Há editais que exigem pagamento da <strong>comissão do leiloeiro (5%)</strong> separadamente</li>
      <li>Alguns editais proíbem financiamento ou exigem entrada mínima</li>
      <li>Prazos de desistência e penalidades variam por edital</li>
    </ul>

    <h2>O que verificar no edital</h2>
    <ul>
      <li><strong>Forma de pagamento:</strong> à vista, financiamento, parcelamento direto</li>
      <li><strong>Prazo para pagamento:</strong> 24h, 5 dias, 30 dias</li>
      <li><strong>Comissão do leiloeiro:</strong> geralmente 5% sobre o valor de arrematação</li>
      <li><strong>ITBI:</strong> quem paga, base de cálculo</li>
      <li><strong>Débitos:</strong> IPTU e condomínio — quem assume</li>
      <li><strong>Ocupação:</strong> ocupado/desocupado, responsabilidade pela desocupação</li>
      <li><strong>Penalidades por desistência:</strong> perda de sinal, multa percentual</li>
    </ul>

    <h2>Como se proteger</h2>
    <ul>
      <li><strong>Leia o edital inteiro</strong> — não apenas o resumo da plataforma</li>
      <li>Destaque e anote os pontos críticos (prazos, custos, penalidades)</li>
      <li>Em caso de dúvida, <strong>consulte um advogado</strong> antes de participar</li>
      <li>Compare o edital com seu orçamento total (imóvel + comissão + ITBI + cartório + débitos)</li>
    </ul>
