    <h2>Quem paga os débitos?</h2>
    <p>A responsabilidade por IPTU e condomínio atrasados em imóveis de leilão/venda da Caixa depende do que diz o edital e da legislação aplicável.</p>

    <h2>IPTU</h2>
    <p>O IPTU é obrigação <em>propter rem</em> (acompanha o imóvel). Em tese, o novo proprietário responde por débitos anteriores. No entanto:</p>
    <ul>
      <li>Em arrematação judicial, o STJ entende que débitos anteriores são sub-rogados no preço (arrematante não paga)</li>
      <li>Em venda direta/extrajudicial da Caixa, depende do edital — muitos transferem a responsabilidade ao comprador</li>
      <li>Verifique SEMPRE o edital e a certidão de débitos na prefeitura</li>
    </ul>

    <h2>Condomínio</h2>
    <p>Também é obrigação <em>propter rem</em>. A jurisprudência majoritária entende que:</p>
    <ul>
      <li>O novo proprietário responde por débitos condominiais anteriores</li>
      <li>Mesmo em leilão, o condomínio pode cobrar do arrematante</li>
      <li>Débitos altos de condomínio (R$ 10k-50k+) podem inviabilizar a compra</li>
    </ul>

    <h2>Como verificar</h2>
    <ul>
      <li><strong>IPTU:</strong> solicitar certidão de débitos na prefeitura municipal</li>
      <li><strong>Condomínio:</strong> solicitar declaração de débitos à administradora ou síndico</li>
      <li>Somar esses valores ao custo total da aquisição</li>
    </ul>

    <h2>Negociação de débitos</h2>
    <ul>
      <li>Prefeituras frequentemente oferecem programas de parcelamento (REFIS)</li>
      <li>Condomínios podem negociar desconto para pagamento à vista</li>
      <li>Use os débitos como argumento para desconto adicional na proposta</li>
