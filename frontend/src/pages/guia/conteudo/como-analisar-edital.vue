    <h2>O que é o edital?</h2>
    <p>O edital é o documento jurídico que rege toda a venda do imóvel. Ele define condições, prazos, responsabilidades e regras. Participar sem ler o edital é como assinar um contrato em branco.</p>

    <h2>O que verificar obrigatoriamente</h2>
    <ul>
      <li><strong>Valor mínimo de venda</strong> — preço abaixo do qual propostas não são aceitas</li>
      <li><strong>Forma de pagamento</strong> — à vista, financiável, parcelamento direto</li>
      <li><strong>Prazo para proposta</strong> — data e hora limites</li>
      <li><strong>Situação de ocupação</strong> — quem é responsável pela desocupação</li>
      <li><strong>Débitos existentes</strong> — IPTU, condomínio, taxas (e quem paga)</li>
      <li><strong>Ônus na matrícula</strong> — penhoras, hipotecas, indisponibilidades</li>
      <li><strong>Condições suspensivas</strong> — situações que podem anular a venda</li>
      <li><strong>Comissão do leiloeiro</strong> — percentual a ser pago pelo comprador (5% é comum)</li>
    </ul>

    <h2>Cláusulas de atenção</h2>
    <ul>
      <li>"O imóvel é vendido no estado em que se encontra" — sem garantia de conservação</li>
      <li>"A desocupação é de responsabilidade do adquirente" — custos judiciais por sua conta</li>
      <li>"Eventuais débitos de IPTU e condomínio serão de responsabilidade do arrematante" — nem sempre é assim, verifique</li>
    </ul>

    <h2>Onde encontrar o edital</h2>
    <p>No portal da Caixa, na página de cada imóvel. O Imovue também disponibiliza link direto quando disponível.</p>

