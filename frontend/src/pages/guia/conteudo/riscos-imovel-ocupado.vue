    <h2>O que significa imóvel ocupado?</h2>
    <p>Um imóvel ocupado é aquele onde ainda há pessoas morando — pode ser o antigo proprietário, inquilinos ou terceiros. Nos editais da Caixa, essa informação aparece como "Ocupado" ou "Desocupado" na descrição.</p>

    <h2>Por que o desconto é maior?</h2>
    <p>Imóveis ocupados geralmente têm descontos de 40-70% justamente pelo risco e custo de desocupação. O mercado precifica esse risco, o que cria oportunidade para quem sabe avaliá-lo.</p>

    <h2>Custos de desocupação</h2>
    <ul>
      <li><strong>Ação de imissão na posse:</strong> R$ 3.000 a R$ 15.000 em honorários advocatícios</li>
      <li><strong>Prazo judicial:</strong> 6 meses a 3 anos dependendo da comarca</li>
      <li><strong>Período sem uso:</strong> você paga IPTU e condomínio sem poder usar o imóvel</li>
      <li><strong>Risco de danos:</strong> ocupante pode danificar o imóvel durante o processo</li>
    </ul>

    <h2>Base legal</h2>
    <p>Para imóveis com alienação fiduciária (maioria da Caixa), a <strong>Lei 9.514/97, art. 30</strong> prevê que o devedor deve desocupar em 60 dias após notificação. Na prática, muitos não saem voluntariamente e é necessária ação judicial.</p>
    <p>Para leilões judiciais, o comprador requer <strong>imissão na posse</strong> ao juiz (art. 625 do CPC).</p>

    <h2>Estratégia "cash for keys"</h2>
    <p>Antes de entrar na Justiça, considere negociar diretamente com o ocupante. Oferecer R$ 3.000 a R$ 10.000 para que saia voluntariamente costuma ser mais rápido e barato que a via judicial.</p>

    <h2>Quando vale a pena?</h2>
    <ul>
      <li>Desconto ≥ 50% sobre o valor de mercado</li>
      <li>Diferença de preço cobre custos estimados de desocupação</li>
      <li>Imóvel para investimento de longo prazo (não precisa de posse imediata)</li>
      <li>Você tem assessoria jurídica especializada</li>
    </ul>

    <h2>Quando evitar?</h2>
    <ul>
      <li>Primeiro imóvel para moradia (precisa de posse rápida)</li>
      <li>Desconto não compensa os custos e prazos de desocupação</li>
      <li>Imóvel em região com Judiciário muito lento</li>
      <li>Sem capital de reserva para custos judiciais</li>
    </ul>

