    <h2>O que é liquidez de um imóvel</h2>
    <p>Liquidez é a facilidade e velocidade com que você consegue vender ou alugar um imóvel pelo preço justo. Um imóvel com alta liquidez encontra comprador ou inquilino em semanas. Um com baixa liquidez pode ficar meses ou anos parado.</p>
    <p>Isso importa porque: se você comprar um imóvel da Caixa com 40% de desconto mas não conseguir vendê-lo depois, o desconto não se realizou. O dinheiro ficou preso.</p>

