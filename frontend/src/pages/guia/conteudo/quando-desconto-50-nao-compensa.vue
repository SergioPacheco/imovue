    <h2>Sinais de que o desconto não compensa</h2>
    <ol>
      <li><strong>Avaliação muito acima dos anúncios da região</strong> — pesquise ZAP, OLX e imobiliárias locais. Se a avaliação da Caixa for 30%+ acima do que imóveis similares pedem, o desconto é inflado.</li>
      <li><strong>Imóvel ocupado + desconto moderado</strong> — a desocupação judicial pode custar R$ 15.000–50.000 e levar 6–24 meses. Só compensa com descontos reais acima de 35%.</li>
      <li><strong>Condomínio com dívida alta</strong> — imóveis abandonados acumulam condomínio. Verifique antes: a dívida é do comprador.</li>
      <li><strong>Região sem demanda</strong> — imóvel com 60% de desconto numa cidade sem mercado de aluguel ou revenda é dinheiro parado.</li>
      <li><strong>Sem financiamento</strong> — se exige pagamento à vista e você precisa usar todo seu capital, o custo de oportunidade é alto.</li>
    </ol>

    <h2>Como verificar o desconto real</h2>
    <ol>
      <li>Pegue o endereço do imóvel</li>
      <li>Pesquise imóveis similares (mesmo bairro, tamanho, tipo) em ZAP Imóveis ou OLX</li>
      <li>Calcule o preço médio por m² da região</li>
      <li>Compare com o preço de venda da Caixa + custos extras (ITBI, cartório, débitos, reforma)</li>
      <li>Se o custo total for menor que 80% do preço de mercado → oportunidade real</li>
    </ol>

    <h2>Quando 50% de desconto VALE a pena</h2>
    <ul>
      <li>Imóvel desocupado em bairro valorizado</li>
      <li>Sem dívidas de condomínio relevantes</li>
      <li>Avaliação da Caixa condizente com o mercado atual</li>
      <li>Aceita financiamento (reduz necessidade de capital)</li>
      <li>Estado de conservação razoável (sem reforma estrutural)</li>
    </ul>

    <h2>Conclusão</h2>
