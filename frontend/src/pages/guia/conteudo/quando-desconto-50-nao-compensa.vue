    <h2>O desconto anunciado é sobre o valor de avaliação — não sobre o mercado</h2>
    <p>A Caixa divulga dois números para cada imóvel: o <strong>valor de avaliação</strong> e o <strong>preço de venda</strong>. O desconto que aparece é a diferença entre esses dois valores. Mas o valor de avaliação é feito pela própria Caixa, em data que pode ser antiga, com critérios que nem sempre refletem a realidade do mercado atual.</p>

