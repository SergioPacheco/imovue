    <h2>Custos obrigatórios na compra</h2>
    <p>Além do preço do imóvel, toda aquisição imobiliária no Brasil envolve três custos obrigatórios: ITBI, escritura pública e registro. Juntos, representam entre 4% e 6% do valor da transação.</p>

    <h2>ITBI — Imposto de Transmissão de Bens Imóveis</h2>
    <p>Imposto municipal cobrado na transferência de propriedade. Características:</p>
    <ul>
      <li><strong>Alíquota:</strong> varia por município, geralmente entre 2% e 3% do valor venal ou transação (o maior)</li>
      <li><strong>Base de cálculo:</strong> pode ser o valor da transação ou o valor venal (definido pela prefeitura)</li>
      <li><strong>Momento:</strong> deve ser pago antes da lavratura da escritura</li>
      <li><strong>Quem paga:</strong> comprador</li>
    </ul>

